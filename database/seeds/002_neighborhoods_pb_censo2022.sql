INSERT INTO public.neighborhoods (name, city_id, owner_id)
SELECT s.neighborhood_name, c.id, '__OWNER_ID__'::uuid
FROM source s
JOIN public.cities c ON c.name = s.city_name
WHERE NOT EXISTS (
  SELECT 1 FROM public.neighborhoods n
  WHERE n.owner_id = '__OWNER_ID__'::uuid
    AND n.city_id = c.id
    AND n.name = s.neighborhood_name
);
